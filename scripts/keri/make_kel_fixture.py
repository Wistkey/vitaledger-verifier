"""Writes test/fixtures/keri-kel.json: a real KEL made with keripy (the KERI
reference implementation), to check the verifier's own KEL code (src/keri.ts).

  python3.12 -m venv .venv && .venv/bin/pip install keri==1.3.6
  .venv/bin/python scripts/keri/make_kel_fixture.py

Throwaway keys in a temporary keystore: nothing here is secret or reused.
"""
import json
import pathlib

from keri.app import habbing
from keri.core import coring, signing

OUT = pathlib.Path(__file__).resolve().parents[2] / "test" / "fixtures" / "keri-kel.json"

# CIP-0170 "Digest computation" test vector: Blake3-256 of the metadatum CBOR.
CIP_BYTES = bytes.fromhex(
    "a36e63726564656e7469616c547970656a6d656d626572736869706d736368656d6156657273696f6e0168"
    "697373756564417474323032362d30382d32305430383a30303a30305a"
)
cip_d = coring.Diger(ser=CIP_BYTES, code=coring.MtrDex.Blake3_256).qb64
assert cip_d == "EOpMIJmAaiP4cZgmDkg8rVtl8YU4dDYf_gxrK2sNdfOR", cip_d

# A label-22092 anchor metadatum, CBOR exactly as test/helpers/encode.ts
# writes it (test/cip170.test.ts asserts that); its digest is anchored last.
ANCHOR_CBOR = bytes.fromhex(
    "a5617601617374766974616c65646765722e7265636f72642e76316172784031653435396530343261343134383835"
    "393134323931336666346239316136323833306338363935393539613661343637653635363464336430663330653238"
    "616e01616976766c3a72656769737472793a766974616c6564676572"
)

seals = []
with habbing.openHby(name="fixture", temp=True, salt=signing.Salter(raw=b"0123456789abcdef").qb64) as hby:
    hab = hby.makeHab(name="vitaledger-fixture", isith="1", icount=1, ncount=1, nsith="1", toad=0, wits=[])
    for i in range(2):
        d = coring.Diger(ser=f"anchor {i}".encode(), code=coring.MtrDex.Blake3_256).qb64
        hab.interact(data=[{"d": d}])
        seals.append({"s": format(hab.kever.sn, "x"), "d": d})
    hab.rotate(isith="1", ncount=1, nsith="1")
    d = coring.Diger(ser=b"after rotation", code=coring.MtrDex.Blake3_256).qb64
    hab.interact(data=[{"d": d}])
    seals.append({"s": format(hab.kever.sn, "x"), "d": d})
    attested_d = coring.Diger(ser=ANCHOR_CBOR, code=coring.MtrDex.Blake3_256).qb64
    hab.interact(data=[{"d": attested_d}])
    attested = {"cborHex": ANCHOR_CBOR.hex(), "d": attested_d, "s": format(hab.kever.sn, "x")}
    kel = bytearray()
    for msg in hab.db.clonePreIter(pre=hab.pre):
        kel.extend(msg)

OUT.write_text(json.dumps({
    "note": "Generated by scripts/keri/make_kel_fixture.py with keripy 1.3.6 (throwaway temp keystore).",
    "aid": hab.pre,
    "kel": bytes(kel).decode(),
    "seals": seals,
    "attested": attested,
    "cip170Vector": {"cborHex": CIP_BYTES.hex(), "d": cip_d},
}, indent=2) + "\n")
print("wrote", OUT, "aid", hab.pre, "events", hab.kever.sn + 1)

// Writes ../../test/fixtures/registry-emulator.json: real (emulator) Conway
// transactions for the verifier's registry tests (src/registry.ts).
//   npx tsx make-fixture.ts
import { writeFileSync } from "node:fs";
import { ed25519 } from "@noble/curves/ed25519.js";
import { bytesToHex } from "@noble/hashes/utils.js";
import { Emulator, Lucid, generateEmulatorAccount } from "@lucid-evolution/lucid";
import { adminKeyHashOf, deployReferenceScriptTx, encodeEntry, registerTx, registryFor, signAll, updateTx, findEntry } from "./lib.js";

const [a1, a2, outsider] = Array.from({ length: 3 }, () => generateEmulatorAccount({ lovelace: 100_000_000n }));
const emulator = new Emulator([a1, a2, outsider]);
const lucid = await Lucid(emulator, "Preprod");
const reg = registryFor("Preprod", { keys: [adminKeyHashOf(a1.address), adminKeyHashOf(a2.address)], required: 2 });
const signing = { signers: [adminKeyHashOf(a1.address), adminKeyHashOf(a2.address)] };

const issuerSecret = ed25519.utils.randomSecretKey();
const pubkey = bytesToHex(ed25519.getPublicKey(issuerSecret));
const recordDigest = "fe1f83fdd5e6f7ff0a8f0aa0a499f91ff1198ecb4f037a725198257d10f656b9";
const signature = bytesToHex(ed25519.sign(new TextEncoder().encode(`vitaledger.record.v1:${recordDigest}`), issuerSecret));
const entry = { issuerId: "vl:issuer:acme-foods", kind: "brand" as const, pubkey, status: "active" as const, updatedAt: 1760000000000n };

async function run(payer: typeof a1, cosign: (typeof a1)[], build: () => ReturnType<typeof registerTx>) {
  lucid.selectWallet.fromSeed(payer.seedPhrase);
  const signed = await signAll(await build(), cosign.map((c) => c.seedPhrase), "Preprod");
  const hash = await signed.submit();
  emulator.awaitBlock(1);
  return { txHash: hash, cborHex: signed.toCBOR() };
}

const register = await run(a1, [a2], () => registerTx(lucid, reg, entry, signing));
const revoke = await run(a1, [a2], async () =>
  updateTx(lucid, reg, await findEntry(lucid, reg, entry.issuerId), { ...entry, status: "revoked", updatedAt: 1760000001000n }, signing),
);
const fake = await run(outsider, [], () =>
  lucid.newTx().pay.ToContract(reg.address, { kind: "inline", value: encodeEntry(entry) }, { lovelace: 2_000_000n }).complete(),
);
const refScript = await run(a1, [], () => deployReferenceScriptTx(lucid, reg));

writeFileSync(
  new URL("../../test/fixtures/registry-emulator.json", import.meta.url),
  JSON.stringify(
    {
      note: "Generated by aiken/scripts/make-fixture.ts in the Lucid Emulator: real Conway transactions, not on any network.",
      policyId: reg.policyId,
      entry: { ...entry, updatedAt: entry.updatedAt.toString() },
      recordDigest,
      signature,
      // Our builders put the registry output first.
      register: { ...register, outputIndex: 0 },
      revoke: { ...revoke, outputIndex: 0 },
      fakeDatumNoToken: { ...fake, outputIndex: 0 },
      referenceScript: { ...refScript, outputIndex: 0 },
    },
    null,
    2,
  ) + "\n",
);
console.log("wrote test/fixtures/registry-emulator.json");

// Writes ../../test/fixtures/cip8-lucid.json: CIP-8 signatures made by Lucid
// Evolution's wallet signMessage (the CIP-30 signData code path), so the
// verifier's own COSE implementation (src/cip8.ts) is checked against an
// independent signer.   npx tsx make-cip8-fixture.ts
import { writeFileSync } from "node:fs";
import { Emulator, Lucid, fromText, generateEmulatorAccount, getAddressDetails } from "@lucid-evolution/lucid";

const account = generateEmulatorAccount({ lovelace: 10_000_000n });
const lucid = await Lucid(new Emulator([account]), "Preprod");
lucid.selectWallet.fromSeed(account.seedPhrase);
const address = await lucid.wallet().address();

const digest = "fe1f83fdd5e6f7ff0a8f0aa0a499f91ff1198ecb4f037a725198257d10f656b9";
const message = `vitaledger.record.v1:${digest}`;
const record = await lucid.wallet().signMessage(address, fromText(message));
const other = await lucid.wallet().signMessage(address, fromText(`vitaledger.record.v1:${"00".repeat(32)}`));

writeFileSync(
  new URL("../../test/fixtures/cip8-lucid.json", import.meta.url),
  JSON.stringify(
    {
      note: "Generated by aiken/scripts/make-cip8-fixture.ts with Lucid Evolution signMessage (CIP-30 signData / CIP-8). Throwaway emulator key.",
      address,
      addressHex: getAddressDetails(address).address.hex,
      recordDigest: digest,
      message,
      signature: record.signature,
      key: record.key,
      signatureOverOtherDigest: other.signature,
    },
    null,
    2,
  ) + "\n",
);
console.log("wrote test/fixtures/cip8-lucid.json");

// Writes ../../test/fixtures/cip170-tx.json: a Lucid Evolution (CML) built
// transaction carrying the anchor in ../../test/fixtures/keri-kel.json at
// label 22092 and a CIP-0170 ATTEST at label 170 that the keripy KEL in that
// file seals. Checks both the TypeScript and Python ATTEST verifiers on real
// CML bytes.   npx tsx make-cip170-fixture.ts
import { readFileSync, writeFileSync } from "node:fs";
import { Emulator, Lucid, generateEmulatorAccount } from "@lucid-evolution/lucid";

const fx = JSON.parse(readFileSync(new URL("../../test/fixtures/keri-kel.json", import.meta.url), "utf8"));
const anchor = { v: 1, s: "vitaledger.record.v1", r: "1e459e042a4148859142913ff4b91a62830c8695959a6a467e6564d3d0f30e28", n: 1, i: "vl:registry:vitaledger" };
const account = generateEmulatorAccount({ lovelace: 10_000_000n });
const lucid = await Lucid(new Emulator([account]), "Preprod");
lucid.selectWallet.fromSeed(account.seedPhrase);
const tx = await lucid
  .newTx()
  .attachMetadata(22092, anchor)
  .attachMetadata(170, { t: "ATTEST", i: fx.aid, d: fx.attested.d, s: fx.attested.s, v: { v: "1.0" } })
  .complete();
const signed = await tx.sign.withWallet().complete();
writeFileSync(
  new URL("../../test/fixtures/cip170-tx.json", import.meta.url),
  JSON.stringify({ note: "Generated by aiken/scripts/make-cip170-fixture.ts (Lucid Evolution / CML, emulator; not on any network).", txHash: signed.toHash(), cborHex: signed.toCBOR() }, null, 2) + "\n",
);
console.log("wrote test/fixtures/cip170-tx.json", signed.toHash());
